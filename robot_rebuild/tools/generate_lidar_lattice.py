"""Generate conservative, NOMINAL fixed-geometry ROM. No calibrated motion model.

For every swept-disc sample, radial exit grows monotonically with the
projection onto the ray. The maximum over a closed angular interval therefore
occurs at an endpoint or the center bearing. No sampled-angle approximation.
The 20 mm segment allowance exceeds half of the 37.5 mm centerline step.
"""
import argparse
import json
import math
from pathlib import Path

PARAMETERS = dict(counts_per_m=7640, wheelbase_mm=100, arc_radius_mm=150,
                 path_length_mm=300, segments=8, body_radius_mm=120,
                 range_error_mm=20, segment_margin_mm=20,
                 input_budget_ms=300, maximum_map_age_ms=350,
                 control_budget_ms=20, decel_mm_s2=200, round_margin_mm=2)

def sector_exit(x, y, radius, sector):
    lo, hi = -math.radians((sector+1)*10), -math.radians(sector*10)
    angles = [lo, hi]
    bearing = math.atan2(y, x)
    for turn in range(-2, 3):
        candidate = bearing + turn*2*math.pi
        if lo <= candidate <= hi:
            angles.append(candidate)
    result = 0.0
    for a in angles:
        projection = x*math.cos(a)+y*math.sin(a)
        disc = radius*radius-x*x-y*y+projection*projection
        if disc >= -1e-8:
            result = max(result, projection+math.sqrt(max(0, disc)))
    return result

def generate():
    rows, candidates = [], []
    for speed in (2, 6, 12):
        v = math.ceil(speed*50000/7640)
        radius = 160+math.ceil(v*670/1000)+math.ceil(v*v/400)
        for direction in range(3):
            centers=[]
            for step in range(9):
                distance=300*step/8
                if direction==1:
                    center=(distance,0)
                else:
                    center=(150*math.sin(distance/150),
                            (1 if direction==0 else -1)*150*(1-math.cos(distance/150)))
                centers.append(center)
            rows.append([math.ceil(max(sector_exit(x,y,radius,s) for x,y in centers)-1e-9)+2
                         for s in range(36)])
            candidates.append(dict(speed_counts=speed, direction=('left','straight','right')[direction],
                                   speed_mm_s=v, inflated_radius_mm=radius, centers_mm=centers))
    return dict(schema=1, status='nominal_unvalidated', parameters=PARAMETERS,
                sector_angle='theta = - raw clockwise angle', candidates=candidates,
                thresholds_mm=rows)

def main():
    parser=argparse.ArgumentParser()
    parser.add_argument('--output-dir',type=Path,default=Path(__file__).resolve().parents[1]/'fpga/rtl')
    args=parser.parse_args()
    data=generate()
    lines=['// Generated by tools/generate_lidar_lattice.py; nominal, unvalidated.',
           '// Fixed parameters and full derivation data: lidar_lattice_rom.json.',
           'module rb_lidar_lattice_rom(input [3:0] candidate, input [5:0] sector, output reg [15:0] threshold_mm);',
           'always @* begin', "  threshold_mm=16'hffff;", '  case ({candidate,sector})']
    for cid,row in enumerate(data['thresholds_mm']):
        for sector,bound in enumerate(row):
            lines.append(f"    10'd{cid*64+sector}: threshold_mm=16'd{bound};")
    lines+=['    default: threshold_mm=16\'hffff;', '  endcase', 'end', 'endmodule', '']
    args.output_dir.mkdir(parents=True,exist_ok=True)
    (args.output_dir/'lidar_lattice_rom.v').write_text('\n'.join(lines))
    (args.output_dir/'lidar_lattice_rom.json').write_text(json.dumps(data,indent=2)+'\n')
    print('Generated 9 x 36 conservative thresholds; nominal geometry, not calibrated.')

if __name__=='__main__':main()
